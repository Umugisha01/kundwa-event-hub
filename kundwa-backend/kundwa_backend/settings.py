def _is_host_connectable(url_str):
    if not url_str:
        return False
    try:
        import urllib.parse, socket
        parsed = urllib.parse.urlparse(url_str.strip())
        if parsed.hostname:
            s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            s.settimeout(1.5)
            s.connect((parsed.hostname, parsed.port or 5432))
            s.close()
            return True
    except Exception:
        return False
    return True

